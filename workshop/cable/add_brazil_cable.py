"""
Add the Brazil-Germany HVDC cable to a composed network (Role 1).

Called from ``scripts/compose_network.py`` for every horizon. Does nothing
unless the config says ``brazil_cable: {enable: true}``, so the baseline and
every other run stay unchanged.

The cable is one PyPSA link, Brazil -> Germany only (p_min_pu = 0):

- ``bus0``: the Brazilian bus. Role 2 owns it. If it does not exist yet, a bare
  AC bus is created at the Natal landing point (no supply, so no flow).
- ``bus1``: the German node (``DE0 7AC``, Wilhelmshaven, agreed with Role 3).
- ``carrier`` and name contain "Brazil", so Role 4's evaluation and the plot
  style recognise it.
- Fixed size, built in ``build_year``; present in every horizon from then on
  until ``build_year + lifetime``. Under myopic foresight the brownfield step
  carries it over; this function only adds it where it is missing.
- ``capital_cost`` is annualised here exactly as scripts/process_cost_data.py
  does it: (annuity(lifetime, discount rate) + FOM) * investment * nyears.

Parameters come from ``workshop/cable/cable_parameters.yaml`` (public,
generated by cable_cost.py). If ``workshop/private/cable_parameters_private.yaml``
exists, its keys override them at runtime (git-ignored; for confidential
inputs, never committed).

Config (all optional except enable):

    brazil_cable:
      enable: true
      level: central          # low | central | high (cable-cost-low/high)
      p_nom: 4000             # MW, overrides the parameter file
      build_year: 2040        # overrides the parameter file
      discount_rate: 0.07     # default: costs.fill_values["discount rate"]
      bus_brazil: Brazil Natal
"""

import logging
from pathlib import Path

import yaml

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]
PARAMS = ROOT / "workshop/cable/cable_parameters.yaml"
PRIVATE = ROOT / "workshop/private/cable_parameters_private.yaml"

# Link and carrier need different names: PyPSA component names must be unique
# across component types (checked in scripts/compose_network.py).
NAME = "Brazil cable Natal-Wilhelmshaven"
CARRIER = "Brazil cable"
DEFAULT_BUS_BRAZIL = "Brazil Natal"
NATAL = (-35.20, -5.78)  # lon, lat of the landing point (public town)


def annuity(n, r):
    return r / (1.0 - 1.0 / (1.0 + r) ** n) if r > 0 else 1.0 / n


def load_parameters(cfg):
    p = yaml.safe_load(PARAMS.read_text())
    if PRIVATE.is_file():
        logger.info("Brazil cable: applying private parameter layer (values not logged)")
        priv = yaml.safe_load(PRIVATE.read_text()) or {}
        for k, v in priv.items():
            if k == "levels":
                for lvl, d in v.items():
                    p["levels"].setdefault(lvl, {}).update(d)
            else:
                p[k] = v
    level = cfg.get("level", "central")
    lv = p["levels"][level]
    return dict(
        level=level,
        bus_brazil=cfg.get("bus_brazil", DEFAULT_BUS_BRAZIL),
        bus_germany=cfg.get("bus_germany", p["bus_germany"]),
        p_nom=float(cfg.get("p_nom", p["p_nom_MW"])),
        build_year=int(cfg.get("build_year", p["build_year"])),
        length=float(p["length_km"]),
        investment=float(lv["investment_EUR_per_MW"]),
        fom=float(lv["FOM_pct_per_a"]),
        lifetime=float(lv["lifetime_a"]),
        efficiency=float(lv["efficiency"]),
        p_max_pu=float(lv["p_max_pu"]),
    )


def add_brazil_cable(n, config, horizon, nyears):
    cfg = config.get("brazil_cable") or {}
    if not cfg.get("enable", False):
        return
    p = load_parameters(cfg)
    if horizon < p["build_year"] or horizon >= p["build_year"] + p["lifetime"]:
        logger.info(f"Brazil cable: not in service in {horizon} (built {p['build_year']})")
        return
    if NAME in n.links.index:
        logger.info(f"Brazil cable: carried over from the previous horizon ({horizon})")
        return

    if p["bus_germany"] not in n.buses.index:
        raise KeyError(f"Brazil cable: German bus {p['bus_germany']!r} not in the network")
    if p["bus_brazil"] not in n.buses.index:
        logger.warning(f"Brazil cable: bus {p['bus_brazil']!r} missing, adding a bare AC bus "
                       "at Natal (no Brazilian supply, so the cable will not carry power)")
        n.add("Bus", p["bus_brazil"], carrier="AC", x=NATAL[0], y=NATAL[1], country="BR",
              v_nom=380.0)
    if CARRIER not in n.carriers.index:
        n.add("Carrier", CARRIER, nice_name=CARRIER)

    r = cfg.get("discount_rate", config["costs"]["fill_values"]["discount rate"])
    capital_cost = (annuity(p["lifetime"], r) + p["fom"] / 100.0) * p["investment"] * nyears

    n.add(
        "Link", NAME,
        bus0=p["bus_brazil"], bus1=p["bus_germany"], carrier=CARRIER,
        p_nom=p["p_nom"], p_nom_extendable=False,
        p_min_pu=0.0, p_max_pu=p["p_max_pu"], efficiency=p["efficiency"],
        length=p["length"], capital_cost=capital_cost,
        build_year=p["build_year"], lifetime=p["lifetime"],
    )
    logger.info(f"Brazil cable: added {p['p_nom']:.0f} MW, level {p['level']}, "
                f"{p['bus_brazil']} -> {p['bus_germany']}, built {p['build_year']}")
